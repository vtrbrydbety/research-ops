"""LangGraph 节点共享的状态模型。

AgentState 是整个工作流的共享状态。各个 LangGraph 节点读取当前状态，
并通过 AgentStateUpdate 返回局部更新，从而完成节点之间的信息传递。
"""

from datetime import datetime, timezone
from typing import Literal, TypedDict
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from researchops.schemas.task import ReproductionPlan, TaskStatus

# LangGraph 工作流允许出现的阶段。
WorkflowStage = Literal[
    "created",
    "normalize_request",
    "generate_plan",
    "validate_plan",
    "finalize",
    "completed",
    "failed",
]

# 单个 Trace 事件允许出现的执行状态。
TraceStatus = Literal[
    "started",
    "success",
    "error",
    "skipped",
]


def utc_now() -> datetime:
    """返回带有时区信息的当前 UTC 时间。"""
    return datetime.now(timezone.utc)


class TraceEvent(BaseModel):
    """工作流执行过程中产生的一条结构化追踪事件。"""

    model_config = ConfigDict(extra="forbid")

    node: str = Field(
        min_length=1,
        description="Graph node that emitted the event.",
    )
    status: TraceStatus = Field(
        description="Execution result associated with the event.",
    )
    timestamp: datetime = Field(
        default_factory=utc_now,
        description="Timezone-aware UTC event timestamp.",
    )
    summary: str = Field(
        min_length=1,
        max_length=1000,
        description="Short human-readable event description.",
    )


class AgentStateUpdate(TypedDict, total=False):
    """LangGraph 节点允许返回的局部状态更新。

    total=False 表示节点不需要返回所有字段，只需返回本节点实际修改的字段。
    """

    normalized_request: str | None
    reproduction_plan: ReproductionPlan | None
    current_stage: WorkflowStage
    status: TaskStatus
    errors: list[str]
    trace: list[TraceEvent]


class AgentState(BaseModel):
    """在所有 LangGraph 节点之间传递的共享状态。"""

    model_config = ConfigDict(
        extra="forbid",
        validate_assignment=True,
        str_strip_whitespace=True,
    )

    task_id: UUID = Field(
        description="Unique task identifier shared across all nodes.",
    )

    # 内部状态允许暂时接收空字符串，由 normalize_request 节点负责
    # 将无效输入转换为结构化错误。外部 TaskRequest 仍然严格拒绝空请求。
    user_request: str = Field(
        max_length=4000,
        description="Original request submitted by the user.",
    )
    normalized_request: str | None = Field(
        default=None,
        description="Request after normalization and intent extraction.",
    )
    reproduction_plan: ReproductionPlan | None = Field(
        default=None,
        description="Structured plan generated by the planner.",
    )
    current_stage: WorkflowStage = Field(
        default="created",
        description="Current graph execution stage.",
    )
    status: TaskStatus = Field(
        default="created",
        description="Current lifecycle status of the task.",
    )
    errors: list[str] = Field(
        default_factory=list,
        description="Safe, user-readable errors accumulated by the graph.",
    )
    trace: list[TraceEvent] = Field(
        default_factory=list,
        description="Structured workflow execution events.",
    )
